            confirmLabel = if (action == TunnelConfirmAction.DELETE) copy.delete else actionLabel,
            dismissLabel = copy.cancel,
            onDismiss = { if (!busy) { confirmAction = null; confirmConfig = null } },
            destructive = action == TunnelConfirmAction.DELETE || action == TunnelConfirmAction.STOP,
            enabled = !busy,
            onConfirm = {
                if (!busy) {
                    confirmAction = null
                    confirmConfig = null
                    when (action) {
                        TunnelConfirmAction.DEPLOY -> deploy(cfg)
                        TunnelConfirmAction.START -> control(cfg, "start")
                        TunnelConfirmAction.STOP -> control(cfg, "stop")
                        TunnelConfirmAction.RESTART -> control(cfg, "restart")
                        TunnelConfirmAction.DELETE -> {
                            val current = records.firstOrNull { it.id == cfg.id }
                            if (current != null && current.name == cfg.name && current.iranHost == cfg.iranHost && current.foreignHost == cfg.foreignHost) {
                                val operationId = operationGate.begin()
                                busy = true
                                error = null
                                retryAction = null
                                job = scope.launch {
                                    try {
                                        check(TunnelEngine.controlRemoteTunnel(context, cfg, "delete")) { copy.tunActionFailedGeneric }
                                        if (!operationGate.owns(operationId)) return@launch
                                        val next = records.filterNot { it.id == cfg.id }
                                        Prefs.saveTunnels(context, next)
                                        records = next
                                        resetForm()
                                        message = copy.tunDeleted
                                    } catch (cancelled: CancellationException) {
                                        throw cancelled
                                    } catch (failure: Exception) {
                                        if (operationGate.owns(operationId)) {
                                            error = SecretRedactor.redact(failure.message ?: copy.tunActionFailedGeneric, listOf(cfg.token)).take(300)
                                            retryAction = {
                                                confirmConfig = cfg
                                                confirmAction = TunnelConfirmAction.DELETE
                                            }
                                        }
                                    } finally {
                                        if (operationGate.owns(operationId)) {
                                            busy = false
                                            job = null
                                        }
                                    }
                                }
                            } else error = copy.tunActionFailedGeneric
                        }
                    }
                }
            }
        )
    }
}

@Composable
private fun CommandBooleanSetting(
    label: String,
    checked: Boolean,
    modifier: Modifier = Modifier,
    onChange: (Boolean) -> Unit
) {
    Row(modifier, verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(CommandSpacing.xxs)) {
        Switch(checked = checked, onCheckedChange = onChange)
        Text(label, color = CommandColors.textSecondary, style = androidx.compose.material3.MaterialTheme.typography.labelSmall)
    }
}
