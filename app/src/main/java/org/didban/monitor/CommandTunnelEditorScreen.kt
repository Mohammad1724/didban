private enum class TunnelConfirmAction {
    DEPLOY,
    START,
    STOP,
    RESTART,
    DELETE
}

@Composable
fun CommandTunnelEditorScreen(
    copy: CommandCopy,
    onBack: () -> Unit
) {
    SecureWindowEffect()
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    var records by remember { mutableStateOf(Prefs.loadTunnels(context)) }
    var selectedId by remember { mutableStateOf<Long?>(null) }
    var name by remember { mutableStateOf("New tunnel") }
    var coreName by remember { mutableStateOf(TunnelCore.BACKPACK.name) }
    var transportName by remember { mutableStateOf(TunnelTransport.STEALTH.name) }
    var iranHost by remember { mutableStateOf("") }
    var iranPort by remember { mutableStateOf("443") }
    var foreignHost by remember { mutableStateOf("") }
    var foreignPort by remember { mutableStateOf("8443") }
    var corePort by remember { mutableStateOf("3080") }
    var token by remember { mutableStateOf("") }
    var preset by remember { mutableStateOf("turbo") }
    var kcpMode by remember { mutableStateOf("fast") }
    var encryption by remember { mutableStateOf("aes-128-gcm") }
    var spoofSrcIp by remember { mutableStateOf("1.1.1.1") }
    var spoofPeerIp by remember { mutableStateOf("8.8.8.8") }
    var virtualIpIran by remember { mutableStateOf("10.200.200.2") }
    var virtualIpForeign by remember { mutableStateOf("10.200.200.1") }
    var mtu by remember { mutableStateOf("1350") }
    var acceptUdp by remember { mutableStateOf(true) }
    var proxyProtocol by remember { mutableStateOf(false) }
    var wsPath by remember { mutableStateOf("/tunnel") }
    var wsHost by remember { mutableStateOf("") }
    var multiPorts by remember { mutableStateOf("") }
    var autoSync by remember { mutableStateOf(true) }
    var discovered by remember { mutableStateOf(false) }
    var enabled by remember { mutableStateOf(true) }
    var message by remember { mutableStateOf<String?>(null) }
    var error by remember { mutableStateOf<String?>(null) }
    var busy by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf<GeneratedTunnelCode?>(null) }
    var artifact by remember { mutableStateOf("Iran config") }
    var confirmAction by remember { mutableStateOf<TunnelConfirmAction?>(null) }
    var confirmConfig by remember { mutableStateOf<TunnelConfig?>(null) }

    fun resetForm() {
        selectedId = null
        name = "New tunnel"
        coreName = TunnelCore.BACKPACK.name
        transportName = TunnelTransport.STEALTH.name
        iranHost = ""
        iranPort = "443"
        foreignHost = ""
        foreignPort = "8443"
        corePort = "3080"
        token = ""
        preset = "turbo"
        kcpMode = "fast"
        encryption = "aes-128-gcm"
        spoofSrcIp = "1.1.1.1"
        spoofPeerIp = "8.8.8.8"
        virtualIpIran = "10.200.200.2"
        virtualIpForeign = "10.200.200.1"
        mtu = "1350"
        acceptUdp = true
        proxyProtocol = false
        wsPath = "/tunnel"
        wsHost = ""
        multiPorts = ""
        autoSync = true
        discovered = false
        enabled = true
        generated = null
        message = null
        error = null
    }

    fun selectTunnel(cfg: TunnelConfig) {
        selectedId = cfg.id
        name = cfg.name
        coreName = cfg.core.name
        transportName = cfg.transport.name
        iranHost = cfg.iranHost
        iranPort = cfg.iranPort.toString()
        foreignHost = cfg.foreignHost
        foreignPort = cfg.foreignPort.toString()
        corePort = cfg.corePort.toString()
        token = cfg.token
        preset = cfg.preset
        kcpMode = cfg.kcpMode
        encryption = cfg.encryption
        spoofSrcIp = cfg.spoofSrcIp
        spoofPeerIp = cfg.spoofPeerIp
        virtualIpIran = cfg.virtualIpIran
        virtualIpForeign = cfg.virtualIpKharej
        mtu = cfg.mtu.toString()
        acceptUdp = cfg.acceptUdp
        proxyProtocol = cfg.proxyProtocol
        wsPath = cfg.wsPath
        wsHost = cfg.wsHost
        multiPorts = cfg.multiPorts
        autoSync = cfg.autoSync
        discovered = cfg.discovered
        enabled = cfg.isEnabled
        generated = null
        message = null
        error = null
    }

    fun buildConfig(): TunnelConfig = TunnelConfig(
        id = selectedId ?: System.currentTimeMillis(),
        name = name.trim().ifBlank { "Tunnel ${selectedId ?: "new"}" },
        core = runCatching { TunnelCore.valueOf(coreName) }.getOrDefault(TunnelCore.BACKPACK),
        transport = runCatching { TunnelTransport.valueOf(transportName) }.getOrDefault(TunnelTransport.STEALTH),
        iranHost = iranHost.trim(),
        iranPort = iranPort.toIntOrNull()?.coerceIn(1, 65535) ?: 443,
        foreignHost = foreignHost.trim(),
        foreignPort = foreignPort.toIntOrNull()?.coerceIn(1, 65535) ?: 8443,
        corePort = corePort.toIntOrNull()?.coerceIn(1, 65535) ?: 3080,
        token = token.trim(),
        preset = preset.trim(),
        kcpMode = kcpMode.trim(),
        encryption = encryption.trim(),
        spoofSrcIp = spoofSrcIp.trim(),
        spoofPeerIp = spoofPeerIp.trim(),
        virtualIpIran = virtualIpIran.trim(),
        virtualIpKharej = virtualIpForeign.trim(),
        mtu = mtu.toIntOrNull()?.coerceIn(576, 9000) ?: 1350,
        acceptUdp = acceptUdp,
        proxyProtocol = proxyProtocol,
        wsPath = wsPath.trim().ifBlank { "/tunnel" },
        wsHost = wsHost.trim(),
        multiPorts = multiPorts.trim(),
        autoSync = autoSync,
        discovered = discovered,
        isEnabled = enabled
    )

    fun persist(cfg: TunnelConfig): Boolean {
        val next = records.toMutableList()
        val index = next.indexOfFirst { it.id == cfg.id }
        if (index >= 0) next[index] = cfg else next.add(cfg)
        return runCatching { Prefs.saveTunnels(context, next) }
            .onSuccess {
                records = next
                selectedId = cfg.id
            }
            .onFailure {
                error = SecretRedactor.redact(it.message ?: copy.tunCodeFailed, listOf(cfg.token)).take(300)
            }
            .isSuccess
    }

    fun saveOnly() {
        val cfg = buildConfig()
        error = null
        if (persist(cfg)) message = copy.tunSaved
    }

    fun generate() {
        val cfg = buildConfig()
        error = null
        message = null
        runCatching { TunnelEngine.generateCode(cfg) }
            .onSuccess {
                token = cfg.token
                if (persist(cfg)) {
                    generated = it
                    message = copy.tunCodeGenerated
                }
            }
            .onFailure { error = SecretRedactor.redact(it.message ?: copy.tunCodeFailed, listOf(cfg.token)).take(300) }
    }

    fun deploy(cfg: TunnelConfig) {
        if (busy) return
        error = null
        if (!persist(cfg)) return
        busy = true
        error = null
        message = copy.tunDeploying
        scope.launch {
            runCatching { TunnelEngine.autoDeployTunnel(context, cfg) }
                .onSuccess { result ->
                    token = cfg.token
                    if (persist(cfg)) {
                        val summary = SecretRedactor.redact(result.summaryMessage, listOf(cfg.token)).take(500)
                        if (result.overallSuccess) message = summary else error = summary
                        generated = null
                    }
                }
                .onFailure { error = SecretRedactor.redact(it.message ?: copy.tunDeployFailed, listOf(cfg.token)).take(300) }
            busy = false
        }
    }

    fun test() {
        val cfg = buildConfig()
        busy = true
        error = null
        scope.launch {
            runCatching { TunnelEngine.testTunnel(cfg) }
                .onSuccess { result ->
                    message = if (result.first) "Tunnel reachable · ${result.second} ms" else "Tunnel unreachable"
                }
                .onFailure { error = SecretRedactor.redact(it.message ?: copy.tunProbeFailed, listOf(cfg.token)).take(300) }
            busy = false
        }
    }

    fun control(cfg: TunnelConfig, action: String) {
        if (busy || action !in setOf("start", "stop", "restart")) return
        val current = records.firstOrNull { it.id == cfg.id }
        if (current == null || current.name != cfg.name || current.iranHost != cfg.iranHost || current.foreignHost != cfg.foreignHost) {
            error = copy.tunActionFailedGeneric
            return
        }
        busy = true
        error = null
        scope.launch {
            runCatching {
                check(TunnelEngine.controlRemoteTunnel(context, cfg, action)) { copy.tunActionFailedGeneric }
            }
                .onSuccess { message = copy.tunActionDone.replace("%1", action) }
                .onFailure { error = SecretRedactor.redact(it.message ?: copy.tunActionFailedGeneric, listOf(cfg.token)).take(300) }
            busy = false
        }
    }

    val artifactText = generated?.let {
        when (artifact) {
            "Foreign config" -> it.foreignConfig
            "Iran install" -> it.iranInstallCommand
            "Foreign install" -> it.foreignInstallCommand
            "Docker Iran" -> it.dockerComposeIran
            "Docker Foreign" -> it.dockerComposeForeign
            else -> it.iranConfig
        }
    }.orEmpty()

    LazyColumn(Modifier.fillMaxSize(), verticalArrangement = Arrangement.spacedBy(CommandSpacing.md)) {
        item {
            Row(Modifier.fillMaxWidth().padding(top = CommandSpacing.sm), verticalAlignment = Alignment.CenterVertically) {
                CommandBackButton(copy.back, onBack)
                CommandSectionTitle(copy.tunnels, if (selectedId == null) copy.tunNewConfiguration else copy.tunEditingId.replace("%1", selectedId.toString()), modifier = Modifier.weight(1f))
            }
        }
        item {
            CommandSurface(raised = true, modifier = Modifier.fillMaxWidth()) {
                Column(Modifier.padding(CommandSpacing.md), verticalArrangement = Arrangement.spacedBy(CommandSpacing.sm)) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Text(copy.tunSavedTunnels, Modifier.weight(1f), style = androidx.compose.material3.MaterialTheme.typography.titleMedium, color = CommandColors.textPrimary)
                        CommandTextButton("New", ::resetForm, icon = Icons.Rounded.Tune)
                    }
                    if (records.isEmpty()) {
                        Text(copy.tunEmptyBody, color = CommandColors.textSecondary, style = androidx.compose.material3.MaterialTheme.typography.bodySmall)
                    } else {
                        Row(Modifier.fillMaxWidth().horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(CommandSpacing.xs)) {
                            records.forEach { cfg ->
                                CommandSecondaryButton(cfg.name, { selectTunnel(cfg) }, enabled = selectedId != cfg.id)
                            }
                        }
                    }
                }
            }
        }
        item {
            CommandSurface(Modifier.fillMaxWidth()) {
                Column(Modifier.padding(CommandSpacing.md), verticalArrangement = Arrangement.spacedBy(CommandSpacing.sm)) {
                    Text(copy.tunIdentityEngine, style = androidx.compose.material3.MaterialTheme.typography.titleMedium, color = CommandColors.textPrimary)
                    OutlinedTextField(name, { name = it }, Modifier.fillMaxWidth(), singleLine = true, label = { Text(copy.tunName) })
                    Text("Core", color = CommandColors.textSecondary, style = androidx.compose.material3.MaterialTheme.typography.labelMedium)
                    Row(Modifier.fillMaxWidth().horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(CommandSpacing.xs)) {
                        TunnelCore.values().forEach { core ->
                            CommandSecondaryButton(core.displayName, { coreName = core.name; generated = null }, enabled = coreName != core.name)
                        }
                    }
                    Text("Transport", color = CommandColors.textSecondary, style = androidx.compose.material3.MaterialTheme.typography.labelMedium)
                    Row(Modifier.fillMaxWidth().horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(CommandSpacing.xs)) {
                        TunnelTransport.values().forEach { transport ->
                            CommandSecondaryButton(transport.displayName, { transportName = transport.name; generated = null }, enabled = transportName != transport.name)
                        }
                    }
                }
            }
        }
        item {
            CommandSurface(Modifier.fillMaxWidth()) {
                Column(Modifier.padding(CommandSpacing.md), verticalArrangement = Arrangement.spacedBy(CommandSpacing.sm)) {
                    Text("Endpoints", style = androidx.compose.material3.MaterialTheme.typography.titleMedium, color = CommandColors.textPrimary)
                    Row(horizontalArrangement = Arrangement.spacedBy(CommandSpacing.sm), modifier = Modifier.fillMaxWidth()) {
                        OutlinedTextField(iranHost, { iranHost = it }, Modifier.weight(1f), singleLine = true, label = { Text(copy.tunIranHost) })
                        OutlinedTextField(iranPort, { iranPort = it.filter(Char::isDigit).take(5) }, Modifier.width(100.dp), singleLine = true, label = { Text("Port") })
                    }
                    Row(horizontalArrangement = Arrangement.spacedBy(CommandSpacing.sm), modifier = Modifier.fillMaxWidth()) {
                        OutlinedTextField(foreignHost, { foreignHost = it }, Modifier.weight(1f), singleLine = true, label = { Text(copy.tunForeignHost) })
                        OutlinedTextField(foreignPort, { foreignPort = it.filter(Char::isDigit).take(5) }, Modifier.width(100.dp), singleLine = true, label = { Text("Port") })
                    }
                    Row(horizontalArrangement = Arrangement.spacedBy(CommandSpacing.sm), modifier = Modifier.fillMaxWidth()) {
                        OutlinedTextField(corePort, { corePort = it.filter(Char::isDigit).take(5) }, Modifier.weight(1f), singleLine = true, label = { Text(copy.tunCorePort) })
                        OutlinedTextField(token, { token = it }, Modifier.weight(2f), singleLine = true, label = { Text(copy.tunRealToken) }, visualTransformation = androidx.compose.ui.text.input.PasswordVisualTransformation())
                    }
                    Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(CommandSpacing.sm)) {
                        CommandSecondaryButton(copy.tunGenerateToken, { token = TunnelEngine.generateRandomToken(24) }, icon = Icons.Rounded.Tune)
                        Text(if (token.isBlank()) copy.tunTokenEmpty else copy.tunTokenSet, color = if (token.isBlank()) CommandColors.warning else CommandColors.success, style = androidx.compose.material3.MaterialTheme.typography.bodySmall)
                    }
                    if (discovered) Text(copy.tunDiscoveryBody, color = CommandColors.warning, style = androidx.compose.material3.MaterialTheme.typography.bodySmall)
                }
            }
        }
        item {
            CommandSurface(Modifier.fillMaxWidth()) {
                Column(Modifier.padding(CommandSpacing.md), verticalArrangement = Arrangement.spacedBy(CommandSpacing.sm)) {
                    Text(copy.tunAdvancedParams, style = androidx.compose.material3.MaterialTheme.typography.titleMedium, color = CommandColors.textPrimary)
                    Row(horizontalArrangement = Arrangement.spacedBy(CommandSpacing.sm), modifier = Modifier.fillMaxWidth()) {
                        OutlinedTextField(preset, { preset = it }, Modifier.weight(1f), singleLine = true, label = { Text("Preset") })
                        OutlinedTextField(kcpMode, { kcpMode = it }, Modifier.weight(1f), singleLine = true, label = { Text(copy.tunKcpMode) })
                        OutlinedTextField(encryption, { encryption = it }, Modifier.weight(1f), singleLine = true, label = { Text("Encryption") })
                    }
                    Row(horizontalArrangement = Arrangement.spacedBy(CommandSpacing.sm), modifier = Modifier.fillMaxWidth()) {
                        OutlinedTextField(wsPath, { wsPath = it }, Modifier.weight(1f), singleLine = true, label = { Text(copy.tunWsPath) })
                        OutlinedTextField(wsHost, { wsHost = it }, Modifier.weight(1f), singleLine = true, label = { Text(copy.tunWsHost) })
                        OutlinedTextField(mtu, { mtu = it.filter(Char::isDigit).take(4) }, Modifier.width(100.dp), singleLine = true, label = { Text("MTU") })
                    }
                    OutlinedTextField(multiPorts, { multiPorts = it }, Modifier.fillMaxWidth(), singleLine = true, label = { Text(copy.tunMultiPortHint) })
                    Row(horizontalArrangement = Arrangement.spacedBy(CommandSpacing.lg), modifier = Modifier.fillMaxWidth()) {
                        CommandBooleanSetting("Accept UDP", acceptUdp) { acceptUdp = it }
                        CommandBooleanSetting("Proxy protocol", proxyProtocol) { proxyProtocol = it }
                        CommandBooleanSetting("Auto sync", autoSync) { autoSync = it }
                        CommandBooleanSetting("Enabled", enabled) { enabled = it }
                    }
                    Row(horizontalArrangement = Arrangement.spacedBy(CommandSpacing.sm), modifier = Modifier.fillMaxWidth()) {
                        OutlinedTextField(spoofSrcIp, { spoofSrcIp = it }, Modifier.weight(1f), singleLine = true, label = { Text(copy.tunSpoofSource) })
                        OutlinedTextField(spoofPeerIp, { spoofPeerIp = it }, Modifier.weight(1f), singleLine = true, label = { Text(copy.tunSpoofPeer) })
                    }
                    Row(horizontalArrangement = Arrangement.spacedBy(CommandSpacing.sm), modifier = Modifier.fillMaxWidth()) {
                        OutlinedTextField(virtualIpIran, { virtualIpIran = it }, Modifier.weight(1f), singleLine = true, label = { Text(copy.tunVirtualIranIp) })
                        OutlinedTextField(virtualIpForeign, { virtualIpForeign = it }, Modifier.weight(1f), singleLine = true, label = { Text(copy.tunVirtualForeignIp) })
                    }
                }
            }
        }
        item {
            Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(CommandSpacing.sm)) {
                CommandPrimaryButton("Save", ::saveOnly, Modifier.weight(1f), Icons.Rounded.Save, enabled = !busy)
                CommandSecondaryButton("Generate", ::generate, Modifier.weight(1f), Icons.Rounded.Tune, enabled = !busy)
            }
        }
        if (selectedId != null) {
            item {
                CommandSurface(raised = true, modifier = Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(CommandSpacing.md), verticalArrangement = Arrangement.spacedBy(CommandSpacing.sm)) {
                        Text(copy.tunRemoteOps, style = androidx.compose.material3.MaterialTheme.typography.titleMedium, color = CommandColors.textPrimary)
                        Text(copy.tunActionsBody, color = CommandColors.textSecondary, style = androidx.compose.material3.MaterialTheme.typography.bodySmall)
                        Row(Modifier.fillMaxWidth().horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(CommandSpacing.xs)) {
                            CommandPrimaryButton("Deploy", { confirmConfig = buildConfig(); confirmAction = TunnelConfirmAction.DEPLOY }, icon = Icons.Rounded.PlayArrow, enabled = !busy)
                            CommandSecondaryButton("Test", ::test, icon = Icons.Rounded.Refresh, enabled = !busy)
                            CommandSecondaryButton("Start", { confirmConfig = buildConfig(); confirmAction = TunnelConfirmAction.START }, icon = Icons.Rounded.PlayArrow, enabled = !busy)
                            CommandSecondaryButton("Stop", { confirmConfig = buildConfig(); confirmAction = TunnelConfirmAction.STOP }, icon = Icons.Rounded.Stop, enabled = !busy)
                            CommandSecondaryButton("Restart", { confirmConfig = buildConfig(); confirmAction = TunnelConfirmAction.RESTART }, icon = Icons.Rounded.Refresh, enabled = !busy)
                            CommandTextButton("Delete", { confirmConfig = buildConfig(); confirmAction = TunnelConfirmAction.DELETE }, icon = Icons.Rounded.DeleteOutline, enabled = !busy)
                        }
                    }
                }
            }
        }
        if (message != null) item { CommandStateBlock("Operation", message ?: "", CommandHealthTone.INFO) }
        if (error != null) item { CommandStateBlock(copy.operationFailed, error ?: "", CommandHealthTone.OFFLINE) }
        if (generated != null) {
            item {
                CommandSurface(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(CommandSpacing.md), verticalArrangement = Arrangement.spacedBy(CommandSpacing.sm)) {
                        Text(copy.tunGeneratedEvidence, style = androidx.compose.material3.MaterialTheme.typography.titleMedium, color = CommandColors.textPrimary)
                        Row(Modifier.fillMaxWidth().horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(CommandSpacing.xs)) {
                            listOf("Iran config", "Foreign config", "Iran install", "Foreign install", "Docker Iran", "Docker Foreign").forEach { key ->
                                CommandSecondaryButton(key, { artifact = key }, enabled = artifact != key)
                            }
                        }
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            Text(artifact, Modifier.weight(1f), color = CommandColors.textSecondary)
                            CommandTextButton("Copy", { SensitiveClipboard.copy(context, "Didban tunnel configuration", artifactText) }, icon = Icons.Rounded.ContentCopy, enabled = artifactText.isNotBlank())
                        }
                        Text(artifactText.ifBlank { copy.noOutput }, color = CommandColors.textPrimary, style = androidx.compose.material3.MaterialTheme.typography.bodySmall.copy(fontFamily = FontFamily.Monospace), maxLines = 60, overflow = TextOverflow.Ellipsis)
                    }
                }
            }
        }
        item { Spacer(Modifier.height(CommandSpacing.xl)) }
    }

    val actionToConfirm = confirmAction
    val configToConfirm = confirmConfig
    if (actionToConfirm != null && configToConfirm != null) {
        val action = actionToConfirm
        val cfg = configToConfirm
        val actionLabel = when (action) {
            TunnelConfirmAction.DEPLOY -> copy.deploy
            TunnelConfirmAction.START -> copy.start
            TunnelConfirmAction.STOP -> copy.stop
            TunnelConfirmAction.RESTART -> copy.restart
            TunnelConfirmAction.DELETE -> copy.delete
        }
        AlertDialog(
            onDismissRequest = { if (!busy) { confirmAction = null; confirmConfig = null } },
            title = { Text(if (action == TunnelConfirmAction.DELETE) copy.tunDeleteTitle else if (action == TunnelConfirmAction.DEPLOY) copy.tunDeployTitle else actionLabel, fontWeight = FontWeight.Bold) },
            text = {
                Text("${if (action == TunnelConfirmAction.DELETE) copy.tunDeleteBody else copy.tunDeployBody}\n\n${cfg.name} · #${cfg.id}\n${cfg.iranHost}:${cfg.iranPort} → ${cfg.foreignHost}:${cfg.foreignPort}\n$actionLabel")
            },
            confirmButton = {
                TextButton(onClick = {
                    if (busy) return@TextButton
                    confirmAction = null
                    confirmConfig = null
                    when (action) {
                        TunnelConfirmAction.DEPLOY -> deploy(cfg)
                        TunnelConfirmAction.START -> control(cfg, "start")
                        TunnelConfirmAction.STOP -> control(cfg, "stop")
                        TunnelConfirmAction.RESTART -> control(cfg, "restart")
                        TunnelConfirmAction.DELETE -> {
                            val current = records.firstOrNull { it.id == cfg.id }
                            if (current != null && current.name == cfg.name && current.iranHost == cfg.iranHost && current.foreignHost == cfg.foreignHost) {
                                busy = true
                                error = null
                                scope.launch {
                                    runCatching {
                                        check(TunnelEngine.controlRemoteTunnel(context, cfg, "delete")) { copy.tunActionFailedGeneric }
                                        val next = records.filterNot { it.id == cfg.id }
                                        Prefs.saveTunnels(context, next)
                                        next
                                    }.onSuccess { next ->
                                        records = next
                                        resetForm()
                                        message = copy.tunDeleted
                                    }.onFailure {
                                        error = SecretRedactor.redact(it.message ?: copy.tunActionFailedGeneric, listOf(cfg.token)).take(300)
                                    }
                                    busy = false
                                }
                            } else error = copy.tunActionFailedGeneric
                        }
                    }
                }, enabled = !busy) { Text(if (action == TunnelConfirmAction.DELETE) copy.delete else actionLabel, color = if (action == TunnelConfirmAction.DELETE || action == TunnelConfirmAction.STOP) CommandColors.danger else CommandColors.accent) }
            },
            dismissButton = { TextButton(onClick = { confirmAction = null; confirmConfig = null }, enabled = !busy) { Text(copy.cancel) } }
        )
    }
}

@Composable
private fun CommandBooleanSetting(label: String, checked: Boolean, onChange: (Boolean) -> Unit) {
    Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(CommandSpacing.xxs)) {
        Switch(checked = checked, onCheckedChange = onChange)
        Text(label, color = CommandColors.textSecondary, style = androidx.compose.material3.MaterialTheme.typography.labelSmall)
    }
}
