    fun resetForm() {
        selectedId = null
        name = copy.tunDefaultName
        coreName = TunnelCore.BACKPACK.name
        transportName = TunnelTransport.STEALTH.name
        iranHost = ""
        iranPort = "443"
        foreignHost = ""
        foreignPort = "8443"
        corePort = "3080"
        token = ""
        preset = "turbo"
        kcpMode = "fast"
        encryption = "aes-128-gcm"
        spoofSrcIp = "1.1.1.1"
        spoofPeerIp = "8.8.8.8"
        virtualIpIran = "10.200.200.2"
        virtualIpForeign = "10.200.200.1"
