    fun selectTunnel(cfg: TunnelConfig) {
        selectedId = cfg.id
        name = cfg.name
        coreName = cfg.core.name
        transportName = cfg.transport.name
        iranHost = cfg.iranHost
        iranPort = cfg.iranPort.toString()
        foreignHost = cfg.foreignHost
        foreignPort = cfg.foreignPort.toString()
        corePort = cfg.corePort.toString()
        token = cfg.token
        preset = cfg.preset
        kcpMode = cfg.kcpMode
        encryption = cfg.encryption
        spoofSrcIp = cfg.spoofSrcIp
        spoofPeerIp = cfg.spoofPeerIp
        virtualIpIran = cfg.virtualIpIran
        virtualIpForeign = cfg.virtualIpKharej
        mtu = cfg.mtu.toString()
        acceptUdp = cfg.acceptUdp
        proxyProtocol = cfg.proxyProtocol
        wsPath = cfg.wsPath
        wsHost = cfg.wsHost
        multiPorts = cfg.multiPorts
        autoSync = cfg.autoSync
        discovered = cfg.discovered
        enabled = cfg.isEnabled
        generated = null
        message = null
        error = null
    }

    fun buildConfig(): TunnelConfig = TunnelConfig(
        id = selectedId ?: System.currentTimeMillis(),
        name = name.trim().ifBlank { copy.tunFallbackName.replace("%1", (selectedId ?: "new").toString()) },
        core = runCatching { TunnelCore.valueOf(coreName) }.getOrDefault(TunnelCore.BACKPACK),
        transport = runCatching { TunnelTransport.valueOf(transportName) }.getOrDefault(TunnelTransport.STEALTH),
        iranHost = iranHost.trim(),
        iranPort = iranPort.toIntOrNull()?.coerceIn(1, 65535) ?: 443,
        foreignHost = foreignHost.trim(),
        foreignPort = foreignPort.toIntOrNull()?.coerceIn(1, 65535) ?: 8443,
        corePort = corePort.toIntOrNull()?.coerceIn(1, 65535) ?: 3080,
        token = token.trim(),
        preset = preset.trim(),
        kcpMode = kcpMode.trim(),
        encryption = encryption.trim(),
        spoofSrcIp = spoofSrcIp.trim(),
        spoofPeerIp = spoofPeerIp.trim(),
        virtualIpIran = virtualIpIran.trim(),
        virtualIpKharej = virtualIpForeign.trim(),
        mtu = mtu.toIntOrNull()?.coerceIn(576, 9000) ?: 1350,
        acceptUdp = acceptUdp,
        proxyProtocol = proxyProtocol,
        wsPath = wsPath.trim().ifBlank { "/tunnel" },
        wsHost = wsHost.trim(),
        multiPorts = multiPorts.trim(),
        autoSync = autoSync,
        discovered = discovered,
        isEnabled = enabled
    )

    fun persist(cfg: TunnelConfig): Boolean {
        val next = records.toMutableList()
        val index = next.indexOfFirst { it.id == cfg.id }
        if (index >= 0) next[index] = cfg else next.add(cfg)
        return runCatching { Prefs.saveTunnels(context, next) }
            .onSuccess {
                records = next
                selectedId = cfg.id
            }
            .onFailure {
                error = SecretRedactor.redact(it.message ?: copy.tunCodeFailed, listOf(cfg.token)).take(300)
            }
            .isSuccess
    }

    fun saveOnly() {
        val cfg = buildConfig()
        error = null
        retryAction = null
        if (persist(cfg)) message = copy.tunSaved
    }

    fun generate() {
        val cfg = buildConfig()
        error = null
        retryAction = null
        message = null
        runCatching { TunnelEngine.generateCode(cfg) }
            .onSuccess {
                token = cfg.token
                if (persist(cfg)) {
                    generated = it
                    message = copy.tunCodeGenerated
                }
            }
            .onFailure {
                error = if (it is IllegalArgumentException) copy.tunValidationFailed
                else SecretRedactor.redact(it.message ?: copy.tunCodeFailed, listOf(cfg.token)).take(300)
            }
    }

    fun cancel() {
        operationGate.cancel()
        job?.cancel()
        job = null
        busy = false
    }

    fun deploy(cfg: TunnelConfig) {
        if (busy) return
        val operationId = operationGate.begin()
        error = null
        if (!persist(cfg)) return
        busy = true
        error = null
        retryAction = null
        message = copy.tunDeploying
        job = scope.launch {
            try {
                val result = TunnelEngine.autoDeployTunnel(context, cfg)
                if (!operationGate.owns(operationId)) return@launch
                token = cfg.token
                if (persist(cfg)) {
                    val summary = SecretRedactor.redact(result.localizedSummary(copy), listOf(cfg.token)).take(500)
                    if (result.overallSuccess) message = summary else {
                        error = summary
                        retryAction = { deploy(cfg) }
                    }
                    generated = null
                }
            } catch (cancelled: CancellationException) {
                throw cancelled
            } catch (failure: Exception) {
                if (operationGate.owns(operationId)) {
                    error = SecretRedactor.redact(failure.message ?: copy.tunDeployFailed, listOf(cfg.token)).take(300)
                    retryAction = { deploy(cfg) }
                }
            } finally {
                if (operationGate.owns(operationId)) {
                    busy = false
                    job = null
                }
            }
        }
    }

    fun test() {
        val cfg = buildConfig()
        if (busy) return
        val operationId = operationGate.begin()
        busy = true
        error = null
        retryAction = null
        job = scope.launch {
            try {
                val result = TunnelEngine.testTunnel(cfg)
                if (operationGate.owns(operationId)) {
                    message = if (result.first) copy.tunReachable.replace("%1", result.second.toString()) else copy.tunUnreachable
                }
            } catch (cancelled: CancellationException) {
                throw cancelled
            } catch (failure: Exception) {
                if (operationGate.owns(operationId)) {
                    error = SecretRedactor.redact(failure.message ?: copy.tunProbeFailed, listOf(cfg.token)).take(300)
                    retryAction = { test() }
                }
            } finally {
                if (operationGate.owns(operationId)) {
                    busy = false
                    job = null
                }
            }
        }
    }

    fun control(cfg: TunnelConfig, action: String) {
        if (busy || action !in setOf("start", "stop", "restart")) return
        val current = records.firstOrNull { it.id == cfg.id }
        if (current == null || current.name != cfg.name || current.iranHost != cfg.iranHost || current.foreignHost != cfg.foreignHost) {
            error = copy.tunActionFailedGeneric
            return
        }
        val operationId = operationGate.begin()
        busy = true
        error = null
        retryAction = null
        job = scope.launch {
            try {
                check(TunnelEngine.controlRemoteTunnel(context, cfg, action)) { copy.tunActionFailedGeneric }
                if (operationGate.owns(operationId)) message = copy.tunActionDone.replace("%1", action)
            } catch (cancelled: CancellationException) {
                throw cancelled
            } catch (failure: Exception) {
                if (operationGate.owns(operationId)) {
                    error = SecretRedactor.redact(failure.message ?: copy.tunActionFailedGeneric, listOf(cfg.token)).take(300)
                    retryAction = { control(cfg, action) }
                }
            } finally {
                if (operationGate.owns(operationId)) {
                    busy = false
                    job = null
                }
            }
        }
    }

    val artifactOptions = listOf(
        "iran-config" to copy.tunArtifactIranConfig,
